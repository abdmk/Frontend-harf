/** محارف لا رسم لها ولا يُنتظر وجودها في الخط (مسافات، وصل، اتجاه) */
const IGNORE = /[\s\u200b-\u200f\u2066-\u2069]/u;

/** الحروف التي في النص وليست في الخط — المتصفّح يرسمها بخط بديل، ونحن نسمّيها */
export function missingChars(text: string, codepoints: ReadonlySet<number>): string[] {
  const out = new Set<string>();
  for (const ch of text) {
    if (IGNORE.test(ch)) continue;
    if (!codepoints.has(ch.codePointAt(0)!)) out.add(ch);
  }
  return [...out];
}
